import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { radarCollectionHealth, loadRadarCollectionHealth } from '../lib/radar-health.js';
const now = Date.parse('2026-09-12T16:00:00Z');
const config = { enabled: true, maxAgeDays: 30, sources: [{ name: 'Fonte', url: 'https://example.test/feed' }] };
const pack = { research: { source: 'Fonte', sourceTitle: 'Notícia de IA', sourceFact: 'Fato publicado na fonte.', sourceUrl: 'https://example.test/news', publishedAt: '2026-09-12T10:00:00Z' } };
const cache = { researchedAt: '2026-09-12T11:16:00Z', packs: [pack, pack] };
const health = c => radarCollectionHealth(config, c, { now });
assert.equal(health(cache).status, 'working');
assert.equal(health(cache).articleCount, 1, 'Variants are not different articles');
assert.equal(health(cache).sourceCount, 1);
assert.match(health(cache).message, /08:16/);
assert.equal(health(null).status, 'fallback');
assert.equal(health({ ...cache, researchedAt: '2026-09-10T15:59:59Z' }).status, 'fallback');
assert.equal(health({ ...cache, researchedAt: '2026-09-13T00:00:00Z' }).status, 'fallback');
assert.equal(health({ ...cache, packs: [] }).status, 'fallback');
assert.equal(health({ ...cache, packs: [{ research: { ...pack.research, publishedAt: '2026-07-01T00:00:00Z' } }] }).articleCount, 0);
assert.equal(health({ ...cache, packs: [{ research: { ...pack.research, sourceUrl: '' } }] }).articleCount, 0);
assert.equal(radarCollectionHealth({ ...config, enabled: false }, cache, { now }).status, 'disabled');
assert.equal(radarCollectionHealth({ ...config, sources: [] }, cache, { now }).status, 'fallback');
assert.equal(radarCollectionHealth(config, cache, { now, live: false }).status, 'unverified');
const fetchImpl = async () => new Response(JSON.stringify({ 'cliente-x': cache }));
assert.equal((await loadRadarCollectionHealth(config, 'cliente-x', { now, fetchImpl })).status, 'working');
assert.equal((await loadRadarCollectionHealth(config, 'cliente-y', { now, fetchImpl })).status, 'fallback');
assert.equal((await loadRadarCollectionHealth(config, 'cliente-x', { now, fetchImpl: async () => new Response('', { status: 503 }) })).status, 'unverified');
assert.equal((await loadRadarCollectionHealth(config, 'cliente-x', { now, fetchImpl: async () => { throw new Error('timeout'); } })).status, 'unverified');
// Regression: tomorrow's mixed educational schedule must not determine collection health.
const api = readFileSync('api/state.js', 'utf8');
assert.ok(api.includes('await loadRadarCollectionHealth(radarConfig, accountKey)'));
assert.ok(!api.includes('tomorrowRadarWorking'));
assert.ok(readFileSync('docs/dashboard.html', 'utf8').includes('body: radar.message ||'));
console.log('PASS: collection evidence, freshness, missing data, variants, account isolation, remote failures, educational schedule independence.');
