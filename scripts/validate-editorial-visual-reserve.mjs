import assert from 'node:assert/strict';
import fs from 'node:fs';
import { pickEditorialVisualReserve } from '../automation/instagram-template/scripts/publish-carousel.mjs';
const groups = JSON.parse(fs.readFileSync('automation/instagram-template/config/content-packs.json'));
const history = JSON.parse(fs.readFileSync('automation/instagram-template/config/publication-history.json'))['cliente-x'];
const packs = groups.find(group => group.account === 'cliente-x').packs;
const candidate = packs.find(pack => pack.editorialReserve);
assert.ok(candidate);
const pick = (items, prior = []) => pickEditorialVisualReserve(items, '2026-10-17', 4, [], prior, () => 0);
const selected = pick(packs);
assert.equal(selected.pack.slides[0].title, candidate.slides[0].title);
assert.match(selected.pack.caption, /Conteúdo educativo autoral/);
assert.ok(!candidate.caption.includes('Conteúdo educativo autoral'));
assert.equal(pick([{...candidate, research:{sourceUrl:'https://example.com/news'}}]).pack, null);
assert.equal(pick([{...candidate, autoGenerated:true}]).pack, null);
assert.equal(pick([{...candidate, editorialReserve:false}]).pack, null);
assert.equal(pick([candidate], [{coverTitle:candidate.slides[0].title}]).pack, null);
if(history.some(e=>e.coverTitle===candidate.slides[0].title))assert.equal(pick([candidate],history).pack,null);
console.log('Reserva revisada inédita aprovada; notícia, geração automática e repetição bloqueadas.');
