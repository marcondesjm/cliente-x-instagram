import { readFileSync, writeFileSync } from 'node:fs';
import { EDUCATION } from '../lib/education-strategy.js';
import { educationEvidence } from '../lib/education-evidence.js';
const base='automation/instagram-template/config/';
const read=name=>JSON.parse(readFileSync(base+name,'utf8'));
const write=(name,value)=>writeFileSync(base+name,JSON.stringify(value,null,2)+'\n');
const accounts=read('accounts.json'), account=accounts.find(a=>a.account==='cliente-x');
if (account.educationStrategy?.enabled) throw new Error('Experimento já configurado; não sobrescrever o estado atual.');
account.educationStrategy={...EDUCATION,enabled:true,ratio:{tutorial:70,news:20,offer:10},previousScheduleUtc:account.scheduleUtc,previousReelScheduleSlots:account.reelScheduleSlots};
account.scheduleUtc=['0 19 * * *']; account.reelScheduleSlots=[];
account.contentProfile.audience='donos de pequenos e grandes negócios que querem reduzir tarefas repetitivas com IA';
account.contentProfile.niche='ensino prático de IA para atendimento, vendas e operação de negócios';
write('accounts.json',accounts);
const bio=read('bio-page.json');
bio.headline='Aprenda a aplicar IA no trabalho do seu negócio';
bio.introText='Exemplos, prompts e passos para melhorar atendimento, vendas e operação. Quer ajuda para avaliar uma tarefa da sua empresa? Comece pela conversa abaixo.';
bio.links[0].title='Conversa sobre IA no seu negócio';
bio.links[0].description='Conte qual tarefa quer melhorar para avaliar possibilidades e próximos passos.';
write('bio-page.json',bio);
const insights=read('performance-insights.json');
const evidence=educationEvidence(insights.accounts?.['cliente-x']?.samples || [],EDUCATION.startDate,insights.updatedAt);
write('education-baseline-20260912.json',{account:'cliente-x',recordedAt:new Date().toISOString(),note:'Snapshot parcial até a coleta indicada. Comparações por formato e idade; não são totais completos da conta.',...evidence});
const records=read('growth-plans.json');
const old=records.find(r=>r.account==='cliente-x');
const plan={...(old?.plan || {}),bio:'IA para donos de pequenos e grandes negócios\nMenos tarefas repetitivas. Mais tempo para vender.\nVeja por onde começar ↓',startDate:EDUCATION.startDate,checks:{...(old?.plan?.checks || {}),audience:true,bio:true,demo:true,offer:true,baseline:true},periods:old?.plan?.periods || {before:{},after:{}}};
write('growth-plans.json',[...records.filter(r=>r.account!=='cliente-x'),{account:'cliente-x',revision:(old?.revision || 0)+1,updatedAt:new Date().toISOString(),plan}]);
console.log(JSON.stringify({startDate:EDUCATION.startDate,reviewDate:EDUCATION.reviewDate,baselineObservations:evidence.observations.length,groups:evidence.groups.length}));
