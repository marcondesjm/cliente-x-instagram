import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { educationKind, educationLessons, nextEducationPack, isBusinessAINews, newsWithPracticalExercise, educationDayBlocked, educationPreview, offerPack, educationForSlot } from '../lib/education-strategy.js';
import { educationEvidence } from '../lib/education-evidence.js';
const read=name=>JSON.parse(readFileSync(`automation/instagram-template/config/${name}`,'utf8'));
const account=read('accounts.json').find(a=>a.account==='cliente-x');
const legacyAccount={...account,educationStrategy:{...account.educationStrategy,mode:'daily'}};
const history=read('publication-history.json')['cliente-x'];
const counts={tutorial:0,news:0,offer:0};
for(let i=0;i<14;i++) counts[educationKind(new Date(Date.parse('2026-09-13T12:00Z')+i*86400000).toISOString().slice(0,10))]++;
assert.deepEqual(counts,{tutorial:10,news:3,offer:1});
assert.equal(educationKind('2026-09-12'),'transition');
assert.equal(educationDayBlocked(legacyAccount,'2026-09-12',[]),true);
assert.equal(educationDayBlocked(legacyAccount,'2026-09-13',[{mediaId:'x',publishedAt:'2026-09-14T02:59:00Z'}]),true);
assert.equal(educationDayBlocked(legacyAccount,'2026-09-13',[{mediaId:'x',publishedAt:'2026-09-14T03:00:00Z'}]),false);
assert.equal(educationDayBlocked({account:'other'},'2026-09-12',[]),false);
assert.deepEqual(account.scheduleUtc,account.educationStrategy.previousScheduleUtc);
assert.equal(account.scheduleUtc.length,13);
assert.ok(!account.reelScheduleSlots.includes(9));
assert.equal(account.scheduleUtc[9],'0 19 * * *');
const workflow=readFileSync('.github/workflows/instagram-feed-cliente-x.yml','utf8');
assert.equal((workflow.match(/- cron:/g)||[]).length,13);
assert.ok(workflow.includes('7 19 * * *'));
assert.equal(nextEducationPack(history).editorialSeries.episode,6);
const simulated=[...history];
for(let i=0;i<13;i++) { const p=nextEducationPack(simulated); assert.ok(p,'Enough tutorials for 14 days even if every news slot falls back'); simulated.push({mediaId:`test-${i}`,education:p.education,editorialSeries:p.editorialSeries}); }
const lessons=educationLessons();
assert.equal(new Set(lessons.map(p=>p.education.lessonId)).size,lessons.length);
for(const p of [...lessons,offerPack()]) { assert.ok(p.caption.length<=2200); assert.ok(p.slides.length>=4); for(const s of p.slides) { assert.ok(s.title && s.body); if(s.imagePath) assert.ok(readFileSync(s.imagePath).length>1000); } }
assert.ok(lessons.every(p=>p.caption.includes('COPIE ESTE PROMPT') && p.caption.includes('SAÍDA ILUSTRATIVA')));
assert.equal(nextEducationPack(history,()=>true),null);
assert.equal(educationPreview(account,'2026-09-13',history)[9].educationKind,'tutorial');
assert.equal(isBusinessAINews({research:{sourceUrl:'https://example.test',sourceTitle:'STF divulga processos',sourceFact:'Uma empresa acompanha o tema.'}}),false);
const news={research:{sourceUrl:'https://example.test',sourceTitle:'IA para atendimento de empresas',sourceFact:'Ferramenta de inteligência artificial ajuda a organizar documentos.',sourceFacts:['Fato confirmado na fonte.']},slides:[{title:'IA para atendimento',body:'Fato'},{title:'Final',body:'Final'}],caption:'Velha chamada'};
assert.equal(isBusinessAINews(news),true);
const practical=newsWithPracticalExercise(news);
assert.ok(practical.caption.includes('EXERCÍCIO PARA O SEU NEGÓCIO')); assert.ok(!practical.caption.includes('Velha chamada')); assert.deepEqual(practical.research,news.research);
const sample={mediaId:'1',publishedAt:'2026-09-10T15:00:00Z',mediaProductType:'FEED',observations:[{windowHours:24,ageHours:25,metrics:{views:4,saved:0,shares:null}}]};
const invalid={...sample,mediaId:'2',observations:[{windowHours:24,ageHours:60,metrics:{views:999}}]};
const result=educationEvidence([sample,sample,invalid]);
assert.equal(result.groups[0].before.posts,1); assert.equal(result.groups[0].after.posts,0);
assert.equal(result.groups[0].before.metrics.saved.median,0); assert.equal(result.groups[0].before.metrics.shares.median,null);
assert.equal(result.groups[0].before.metrics.views.median,4);
assert.equal(educationPreview(account,'2026-09-13',history).length,13);
assert.equal(educationPreview(account,'2026-09-13',history).filter(p=>p.educationKind).length,1);
for(let i=0;i<13;i++) assert.equal(educationForSlot(account,'2026-09-13',i),i===9);
assert.equal(educationForSlot(account,'2026-09-12',9),false);
assert.equal(educationDayBlocked(account,'2026-09-13',[{mediaId:'news',publishedAt:'2026-09-13T12:00:00Z'}]),false);
assert.equal(educationDayBlocked(account,'2026-09-13',[{mediaId:'lesson',education:{strategy:account.educationStrategy.id},publishedAt:'2026-09-13T19:10:00Z'}]),true);
assert.equal(educationPreview(account,'2026-09-16',history)[9].educationKind,'tutorial');
console.log(`PASS: 14-day mix, ${lessons.length} lessons, transition, daily limit/BRT, duplicate exclusion, news relevance, immutable facts, observed windows, missing vs zero, matching schedule.`);
