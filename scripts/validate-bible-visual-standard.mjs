import assert from 'node:assert/strict';
import fs from 'node:fs';
import { bibleVisualIssues, visualReadyPacks, assertBibleVisualStandard } from '../lib/bible-visual-standard.js';
const accounts=JSON.parse(fs.readFileSync('automation/instagram-template/config/accounts.json'));
const kids=accounts.find(a=>a.account==='sabedoria-kids');
const packs=JSON.parse(fs.readFileSync('automation/instagram-template/config/content-packs.json')).find(g=>g.account==='sabedoria-kids').packs;
const ready=visualReadyPacks(packs,kids,p=>fs.existsSync(p));
const abraham=packs.find(p=>p.id==='kids-biblia-05');
assert.equal(bibleVisualIssues(abraham,p=>fs.existsSync(p)).length,0);
assert.ok(ready.length>=7);
const missing=structuredClone(abraham);delete missing.slides[2].imagePath;
assert.throws(()=>assertBibleVisualStandard(missing,kids),/cartão 3/);
assert.equal(visualReadyPacks([missing],kids).length,0);
assert.throws(()=>assertBibleVisualStandard(abraham,kids,()=>false),/disponível/);
const repeated=structuredClone(abraham);repeated.storySlide.imagePath=repeated.slides[0].imagePath;
assert.throws(()=>assertBibleVisualStandard(repeated,kids),/Story repete/);
const noLicense=structuredClone(abraham);delete noLicense.illustrationSource;
assert.throws(()=>assertBibleVisualStandard(noLicense,kids),/licença/);
const other=accounts.find(a=>a.account==='cliente-x');
assert.equal(visualReadyPacks([missing],other).length,1);
assert.doesNotThrow(()=>assertBibleVisualStandard(missing,other));
console.log(`PASS: ${ready.length}/${packs.length} pautas ilustradas; sem imagem, arquivo, crédito ou Story distinto bloqueados, outras contas preservadas.`);
